// Runs after `next build` (npm's postbuild step). Writes out/sw.js: a service worker that saves
// every file of the built site on the first visit, so the whole course then works offline.
//
// The cache is named after a hash of every file, so each deploy gets a fresh cache and the
// old one is deleted. Browsers check sw.js on each visit and pick up a new version by themselves.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const files = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(OUT);

const hash = createHash("sha256");
const urls = [];
for (const p of files.sort()) {
  const rel = relative(OUT, p).split(sep).join("/");
  // skip the worker itself, hidden files and source maps
  if (rel === "sw.js" || rel.split("/").some((s) => s.startsWith(".")) || rel.endsWith(".map")) continue;
  hash.update(rel).update(readFileSync(p));
  // pages are requested as their folder ("study/"), not "study/index.html"
  urls.push(rel === "index.html" ? "./" : rel.endsWith("/index.html") ? rel.slice(0, -"index.html".length) : rel);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs: don't edit by hand.
const CACHE = "kowhai-${version}";
const FILES = ${JSON.stringify(urls)};

// install: save the whole site (relative to where the site lives)
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new URL(f, self.registration.scope)))));
  self.skipWaiting();
});

// activate: delete the caches of older versions
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("kowhai-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// fetch: saved copy first (query strings like ?drill= don't matter), the network for anything else
self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || !req.url.startsWith(self.registration.scope)) return;
  event.respondWith(
    caches.open(CACHE).then(async (c) => {
      const hit = await c.match(req, { ignoreSearch: true, ignoreVary: true });
      if (hit) return hit;
      try {
        return await fetch(req);
      } catch (err) {
        // offline and not saved: show the site's own "page not found"
        if (req.mode === "navigate") return (await c.match(new URL("404.html", self.registration.scope))) ?? Response.error();
        throw err;
      }
    }),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files, cache kowhai-${version}`);
